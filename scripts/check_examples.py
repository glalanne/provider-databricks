import os
import shutil
import sys

import yaml


def load_gvks(path, loader):
    types = set()
    for root, _, files in os.walk(path):
        for f in files:
            if f.endswith(".yaml"):
                with open(os.path.join(root, f)) as s:
                    for t in yaml.safe_load_all(s):
                        for gvk in loader(t):
                            types.add(gvk)
    return types


def copy_missing_files(source_dir, destination_dir):
    copied = []
    for root, _, filenames in os.walk(source_dir):
        for filename in filenames:
            source = os.path.join(root, filename)
            relative_path = os.path.relpath(source, source_dir)
            destination = os.path.join(destination_dir, relative_path)
            if os.path.exists(destination):
                continue
            os.makedirs(os.path.dirname(destination), exist_ok=True)
            shutil.copy2(source, destination)
            copied.append((source, destination))
    return copied


def load_crd_type(t):
    kind = t["spec"]["names"]["kind"]
    group = t["spec"]["group"]
    for v in t["spec"]["versions"]:
        yield f'{kind}.{group}/{v["name"]}'


exception_set = {
    "ProviderConfigUsage.databricks.crossplane.io/v1beta1",
    "ProviderConfigUsage.databricks.m.crossplane.io/v1beta1",
    # HACK: These are not generated by Upjet, but are required for the provider to work.
    # Need more investigation to see if we can remove these exceptions.
    "KnowledgeAssistant.ai.databricks.m.crossplane.io/v1beta1",
    "KnowledgeAssistant.ai.databricks.crossplane.io/v1beta1",
    "KnowledgeAssistantKnowledgeSource.ai.databricks.m.crossplane.io/v1beta1",
    "KnowledgeAssistantKnowledgeSource.ai.databricks.crossplane.io/v1beta1",
    "SupervisorAgentTool.ai.databricks.m.crossplane.io/v1beta1",
    "SupervisorAgent.ai.databricks.m.crossplane.io/v1beta1",
    "SupervisorAgentTool.ai.databricks.crossplane.io/v1beta1",
    "SupervisorAgent.ai.databricks.crossplane.io/v1beta1",
}

# Example usage: check_examples.py <CRD dir> <example manifests dir> [--fix-missing]
if __name__ == "__main__":
    if len(sys.argv) not in (3, 4) or (
        len(sys.argv) == 4 and sys.argv[3] != "--fix-missing"
    ):
        print(
            "Example usage: check_examples.py <CRD dir> <example manifests dir> [--fix-missing]"
        )
        sys.exit(1)
    crd_dir = sys.argv[1]
    examples_dir = sys.argv[2]
    fix_missing = len(sys.argv) == 4
    known_crd_types = load_gvks(crd_dir, load_crd_type)
    example_types = load_gvks(
        examples_dir,
        lambda t: (
            []
            if t is None or not {"kind", "apiVersion"}.issubset(t.keys())
            else [f'{t["kind"]}.{t["apiVersion"]}']
        ),
    )
    diff = known_crd_types.difference(example_types.union(exception_set))
    if len(diff) == 0:
        print("All CRDs have at least one example...")
        print(f"Exceptions allowed for: {exception_set}")
        sys.exit(0)

    if fix_missing:
        generated_dir = os.path.join(
            os.path.dirname(examples_dir),
            f"{os.path.basename(examples_dir)}-generated",
        )
        generated_types = load_gvks(
            generated_dir,
            lambda t: (
                []
                if t is None or not {"kind", "apiVersion"}.issubset(t.keys())
                else [f'{t["kind"]}.{t["apiVersion"]}']
            ),
        )
        for source, destination in copy_missing_files(generated_dir, examples_dir):
            print(f"Copied {source} -> {destination}")

        for gvk in sorted(diff.difference(generated_types)):
            print(f"No generated example found for {gvk}", file=sys.stderr)
        example_types = load_gvks(
            examples_dir,
            lambda t: (
                []
                if t is None or not {"kind", "apiVersion"}.issubset(t.keys())
                else [f'{t["kind"]}.{t["apiVersion"]}']
            ),
        )
        diff = known_crd_types.difference(example_types.union(exception_set))
        if len(diff) == 0:
            print("All CRDs have at least one example after fixing missing files...")
            sys.exit(0)
    print(f"Please add example manifests for the following types: {diff}")
    sys.exit(2)
